"""Byte-preserving boundary between generated Markdown and user notes."""
import hashlib
import re

START = b'<!-- sno2md:generated:start -->'
END = b'<!-- sno2md:generated:end -->'
DEFAULT_USER = '\n## 사용자 메모\n'.encode('utf-8')
PAGE_USER = '\n### 사용자 메모\n\n'.encode('utf-8')
PAGE_MARKER = re.compile(rb'<!-- sno2md:page-user:(start|end):([0-9a-f]{64}) -->')


def digest(data):
    return hashlib.sha256(data).hexdigest()


def _layout(data):
    lines = data.splitlines(keepends=True)
    starts = [i for i, line in enumerate(lines) if line.rstrip(b'\r\n') == START]
    ends = [i for i, line in enumerate(lines) if line.rstrip(b'\r\n') == END]
    if len(starts) != 1 or len(ends) != 1 or starts[0] >= ends[0]:
        raise ValueError('Markdown generated boundaries are missing, duplicated or out of order')
    start, end = starts[0], ends[0]
    if (not lines or lines[0].rstrip(b'\r\n') != b'---' or start < 2
            or lines[start-1].rstrip(b'\r\n') != b'---'
            or any(line.rstrip(b'\r\n') == b'---' for line in lines[1:start-1])
            or not lines[end].endswith(b'\n')):
        raise ValueError('Markdown boundary must immediately follow frontmatter and end with a newline')
    offset = sum(map(len, lines[:end+1]))
    slots, opened, seen = [], None, set()
    position = 0
    for i, line in enumerate(lines):
        value = line.rstrip(b'\r\n')
        if value.startswith(b'<!-- sno2md:page-user:'):
            marker = PAGE_MARKER.fullmatch(value)
            if not marker or not start < i < end or not line.endswith(b'\n'):
                raise ValueError('invalid Markdown page user boundary')
            kind, key = marker.groups()
            if kind == b'start':
                if opened is not None or key in seen:
                    raise ValueError('duplicate or nested Markdown page user boundary')
                opened = (key, position, position + len(line))
                seen.add(key)
            else:
                if opened is None or opened[0] != key:
                    raise ValueError('Markdown page user boundaries are out of order')
                slots.append((*opened, position, position + len(line)))
                opened = None
        position += len(line)
    if opened is not None:
        raise ValueError('Markdown page user boundary is missing')
    return offset, slots


def split(data):
    """Return generated bytes (excluding inline notes) and legacy document notes.

    For schema 3 the first value is a hash projection, not a complete document.
    Use merge() to publish a document with its inline user content intact.
    """
    offset, slots = _layout(data)
    chunks, previous = [], 0
    for key, start, content, stop, end in slots:
        chunks.append(data[previous:content])
        previous = stop
    chunks.append(data[previous:offset])
    return b''.join(chunks), data[offset:]


def page_user(identity):
    key = digest(identity.encode('utf-8')).encode('ascii')
    return (b'<!-- sno2md:page-user:start:' + key + b' -->\n' + PAGE_USER
            + b'<!-- sno2md:page-user:end:' + key + b' -->\n')


def merge(new, current):
    """Preserve each page's exact note bytes by ID, plus existing document notes."""
    old_offset, old_slots = _layout(current)
    new_offset, new_slots = _layout(new)
    existing = {key: current[start:end] for key, start, content, stop, end in old_slots}
    chunks, previous = [], 0
    for key, start, content, stop, end in new_slots:
        chunks.extend((new[previous:start], existing.pop(key, new[start:end])))
        previous = end
    # Retain removed pages inside the generated envelope. If their IDs return,
    # their notes are reattached to the matching page on the next conversion.
    envelope = new[:new_offset]
    end_start = envelope.rfind(END)
    chunks.append(new[previous:end_start])
    if existing:
        chunks.append('\n## 원본에서 사라진 페이지의 메모\n\n'.encode('utf-8'))
        for number, block in enumerate(existing.values(), 1):
            chunks.append(f'### 보존된 메모 {number}\n\n'.encode('utf-8') + block)
    chunks.extend((new[end_start:new_offset], current[old_offset:]))
    result = b''.join(chunks)
    split(result)
    return result


def create(frontmatter, body):
    data = frontmatter + START + b'\n' + body + b'\n' + END + b'\n' + DEFAULT_USER
    split(data)  # Reject reserved marker lines in extracted source text, too.
    return data
